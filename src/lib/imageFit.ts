// משבצות התצוגה (באנר הכרטיס, תמונת השער בעמוד הגמ"ח) הן קופסאות ביחס
// קבוע עם object-cover. תמונה רחבה או גבוהה בהרבה מהקופסה נחתכת עד כדי
// רצועה צרה — פנורמת שולחן-שבת הופכת לזום על שלושה סועדים. מעבר לספים
// האלה המציגים עוברים ל-object-contain: כל התמונה נראית, והשוליים
// נצבעים ברקע הכהה של המשבצת.
// ============================================================

/** רחבה מ-16:9 בערך, או גבוהה מ-3:5 — יחס שמשבצת ריבועית-בקירוב חותכת קשה */
export function isExtremeAspect(img: HTMLImageElement): boolean {
    const w = img.naturalWidth;
    const h = img.naturalHeight;
    if (!w || !h) return false;
    const ratio = w / h;
    return ratio > 1.7 || ratio < 0.6;
}
